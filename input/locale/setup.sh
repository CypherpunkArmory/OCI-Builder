#!/bin/sh
# Locales for the languages UserLAnd is translated into, so the guest can follow the phone's
# language: the app writes /etc/default/locale with the closest of them (see the app's
# GuestLocale), choosing only from the list left in /usr/share/userland/locales. Run once while
# building an image, before its packages are installed where the distribution would otherwise
# leave their translations out (Ubuntu, Fedora).
set -e
LOCALES="ar_SA ca_ES de_DE en_GB en_US es_ES es_MX fa_IR fr_FR hi_IN id_ID it_IT ja_JP ko_KR pl_PL
         pt_BR pt_PT ru_RU tr_TR vi_VN zh_CN zh_TW"
. /etc/os-release
LANGS="ar ca de en es fa fr hi id it ja ko pl pt ru tr vi zh"

debian_family() {
  apt-get update
  apt-get install -y --no-install-recommends locales

  if [ "$ID" = ubuntu ]; then
    # Ubuntu's minimized image drops every translation, and Ubuntu moves those of its main
    # packages into language packs (some 200 MB for these languages): keep translations from now
    # on, and take only the core tools' from the packs.
    sed -i '\#^path-exclude=/usr/share/locale/\*/LC_MESSAGES/\*.mo#d' /etc/dpkg/dpkg.cfg.d/excludes
    packs=""
    for l in $LOCALES; do
      case "$l" in zh_CN) p=zh-hans ;; zh_TW) p=zh-hant ;; *) p=${l%_*} ;; esac
      case " $packs " in *" $p "*) ;; *) packs="$packs $p" ;; esac
    done
    apt-get install -y --no-install-recommends $(for p in $packs; do echo language-pack-$p-base; done)
    /usr/share/userland/keep-langpack.sh libc coreutils bash apt dpkg debconf findutils grep sed tar \
      gzip diffutils util-linux procps-ng shadow sudo nano wget adduser
    apt-get purge -y $(for p in $packs; do echo language-pack-$p-base language-pack-$p; done) || true
  fi

  # Registered where the distribution's locale-gen reads them, and generated by it, so they
  # survive it running again: when the locales package is upgraded, or (Ubuntu) a language pack
  # is removed, as above.
  if [ "$ID" = ubuntu ]; then
    mkdir -p /var/lib/locales/supported.d
    for l in $LOCALES; do echo "$l.UTF-8 UTF-8"; done > /var/lib/locales/supported.d/userland
  else
    for l in $LOCALES; do echo "$l.UTF-8 UTF-8"; done >> /etc/locale.gen
  fi
  locale-gen
  apt-get clean
  rm -rf /var/lib/apt/lists/*
}

fedora() {
  # Fedora's container image installs English only (%_install_langs): keep the app's languages'
  # translations from now on, add their locales, and reinstall the core tools for theirs.
  sed -i "s/^%_install_langs .*/%_install_langs $(echo $LANGS | tr ' ' ':')/" /etc/rpm/macros.image-language-conf
  dnf install -y --setopt=install_weak_deps=False $(for l in $LANGS; do echo glibc-langpack-$l; done)
  dnf reinstall -y $(rpm -q --qf '%{NAME}\n' coreutils-common bash util-linux sudo nano dnf5 2>/dev/null | grep -v 'not installed')
  dnf clean all
}

arch_linux() {
  for l in $LOCALES; do echo "$l.UTF-8 UTF-8"; done >> /etc/locale.gen
  locale-gen
  # Arch's own profile (and systemd) read /etc/locale.conf, which the image sets to en_US:
  # point it at the app's choice instead. `localectl set-locale` replaces the link, and wins.
  mkdir -p /etc/default
  ln -sf default/locale /etc/locale.conf
}

alpine() {
  # musl loads any UTF-8 locale by name; musl-locales adds its translations and `locale`.
  apk add --no-cache musl-locales musl-locales-lang
}

case "$ID" in
  debian|ubuntu|kali) debian_family ;;
  fedora) fedora ;;
  arch|archarm) arch_linux ;;
  alpine) alpine ;;
  *) echo "setup.sh: no locales for $ID" >&2; exit 1 ;;
esac

# The ones the image can load, for the app to choose from, and where it writes its choice
mkdir -p /usr/share/userland /etc/default
for l in $LOCALES; do
  if [ "$(LC_ALL=$l.UTF-8 locale charmap 2> /dev/null)" = UTF-8 ]; then echo "$l.UTF-8"; fi
done > /usr/share/userland/locales

# Logins (the terminal's SSH, which goes through no PAM) read the locale the app chose.
# Unless the login has one of its own: the distribution's profile may already have set a
# default (Alpine, Fedora and Arch set C.UTF-8), which this replaces.
printf '# The locale the app chose (/etc/default/locale); see /usr/share/userland/locale.sh.\ncase "$LANG" in ""|C|C.UTF-8|C.utf8|POSIX) unset LANG; . /usr/share/userland/locale.sh ;; esac\n' \
  > /etc/profile.d/userland-locale.sh
chmod +x /etc/profile.d/userland-locale.sh
